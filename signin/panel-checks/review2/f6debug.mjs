import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE = 'http://127.0.0.1:8077';
const real = fs.readFileSync('/home/user/openspineconsortium.github.io/assets/js/symphony-panel.js', 'utf8');
const browser = await chromium.launch();
const context = await browser.newContext();
const calls = [];
let refuse = false;
await context.route('https://api.github.com/**', async (route) => {
  const req = route.request(); const url = new URL(req.url()); const key = req.method() + ' ' + url.pathname; const auth = req.headers()['authorization'] || '';
  calls.push(key + ' ' + auth);
  const h = { 'Access-Control-Expose-Headers': 'Link' };
  if (key === 'GET /user') return route.fulfill({ status: 200, contentType: 'application/json', headers: h, body: JSON.stringify({ login: 'tester' }) });
  if (/^GET \/repos\/acme\/(demo|two)$/.test(key)) return route.fulfill({ status: 200, contentType: 'application/json', headers: h, body: JSON.stringify({ full_name: url.pathname.slice(7), private: false }) });
  if (key === 'GET /repos/acme/demo/contents/METRICS.json' && refuse && auth === 'Bearer github_pat_ONE') return route.fulfill({ status: 401, contentType: 'application/json', headers: h, body: JSON.stringify({ message: 'Bad credentials' }) });
  return route.fulfill({ status: 404, contentType: 'application/json', headers: h, body: JSON.stringify({ message: 'Not Found' }) });
});
await context.route('**/assets/js/symphony-panel.js*', (route) => route.fulfill({ status: 200, contentType: 'application/javascript', body: real }));
const page = await context.newPage();
await page.goto(BASE + '/symphony/cost.html');
await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); localStorage.setItem('symphony_panel_token', 'github_pat_ONE'); localStorage.setItem('symphony_panel_repos', JSON.stringify(['acme/demo', 'acme/two'])); localStorage.setItem('symphony_panel_repo', 'acme/demo'); });
await page.goto(BASE + '/symphony/cost.html');
await page.waitForSelector('#cp-app:not(.hidden)');
await page.waitForFunction(() => /no branch metrics yet/.test(document.getElementById('cost-measured').textContent));
refuse = true;
await page.selectOption('#cost-repo', 'acme/two');
await new Promise((r) => setTimeout(r, 400));
await page.selectOption('#cost-repo', 'acme/demo');
await page.waitForSelector('#cp-gate:not(.hidden)', { timeout: 5000 });
console.log('gate after 401; msg:', await page.textContent('#msg'));
await page.fill('#cp-token', 'github_pat_TWO');
await page.click('#cp-open');
await page.waitForSelector('#cp-app:not(.hidden)');
await new Promise((r) => setTimeout(r, 600));
console.log('select value now:', await page.$eval('#cost-repo', (s) => s.value));
const before = calls.length;
await page.selectOption('#cost-repo', 'acme/two');
await new Promise((r) => setTimeout(r, 800));
console.log(calls.slice(before).join('\n'));
await browser.close();
